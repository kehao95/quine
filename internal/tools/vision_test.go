func TestHandleVisionReturnsImagePayload(t *testing.T) {
	tmpDir := t.TempDir()
	path := filepath.Join(tmpDir, "sample.png")
	if err := os.WriteFile(path, encodePNG(t, 8, 8, color.RGBA{R: 255, A: 255}), 0o644); err != nil {
		t.Fatalf("write sample image: %v", err)
	}

	result := HandleVision("vision-1", map[string]any{
		"path":        path,
		"instruction": "name the dominant color",
	})
	if result.IsError {
		t.Fatalf("HandleVision() returned error: %s", string(result.Content))
	}
	if result.Image == nil {
		t.Fatal("HandleVision() returned nil image payload")
	}
	if result.Image.MIMEType != "image/png" {
		t.Fatalf("image mime = %q, want image/png", result.Image.MIMEType)
	}

	payload := decodeVisionPayload(t, result)
	if payload["status"] != "completed" {
		t.Fatalf("status = %#v, want completed", payload["status"])
	}
	if payload["mime_type"] != "image/png" {
		t.Fatalf("mime_type = %#v, want image/png", payload["mime_type"])
	}
	if payload["instruction"] != "name the dominant color" {
		t.Fatalf("instruction = %#v", payload["instruction"])
	}
}

func TestHandleVisionConvertsPPMToPNG(t *testing.T) {
	tmpDir := t.TempDir()
	path := filepath.Join(tmpDir, "sample.ppm")
	data := []byte("P6\n# generated by a benchmark probe\n2 1\n255\n\xff\x00\x00\x00\xff\x00")
	if err := os.WriteFile(path, data, 0o644); err != nil {
		t.Fatalf("write sample ppm: %v", err)
	}

	result := HandleVision("vision-ppm", map[string]any{"path": path})
	if result.IsError {
		t.Fatalf("HandleVision() returned error: %s", string(result.Content))
	}
	if result.Image == nil {
		t.Fatal("HandleVision() returned nil image payload")
	}
	if result.Image.MIMEType != "image/png" {
		t.Fatalf("image mime = %q, want image/png", result.Image.MIMEType)
	}

	decoded, err := base64.StdEncoding.DecodeString(result.Image.Data)
	if err != nil {
		t.Fatalf("decode image payload: %v", err)
	}
	img, format, err := image.Decode(bytes.NewReader(decoded))
	if err != nil {
		t.Fatalf("decode converted image: %v", err)
	}
	if format != "png" {
		t.Fatalf("converted image format = %q, want png", format)
	}
	if bounds := img.Bounds(); bounds.Dx() != 2 || bounds.Dy() != 1 {
		t.Fatalf("converted image bounds = %v, want 2x1", bounds)
	}

	payload := decodeVisionPayload(t, result)
	if payload["mime_type"] != "image/png" {
		t.Fatalf("mime_type = %#v, want image/png", payload["mime_type"])
	}
}

