func encodePNG(t *testing.T, width, height int, c color.Color) []byte {
	t.Helper()
	img := image.NewRGBA(image.Rect(0, 0, width, height))
	for y := 0; y < height; y++ {
		for x := 0; x < width; x++ {
			img.Set(x, y, c)
		}
	}
	var buf bytes.Buffer
	if err := png.Encode(&buf, img); err != nil {
		t.Fatalf("encode png: %v", err)
	}
	return buf.Bytes()
}

func encodeJPEG(t *testing.T, width, height int, c color.Color) []byte {
	t.Helper()
	img := image.NewRGBA(image.Rect(0, 0, width, height))
	for y := 0; y < height; y++ {
		for x := 0; x < width; x++ {
			img.Set(x, y, c)
		}
	}
	var buf bytes.Buffer
	if err := jpeg.Encode(&buf, img, &jpeg.Options{Quality: 90}); err != nil {
		t.Fatalf("encode jpeg: %v", err)
	}
	return buf.Bytes()
}

func decodeVisionPayload(t *testing.T, result tape.ToolResult) map[string]any {
	t.Helper()
	payload, err := tape.UnmarshalStructuredToolResultContent(result.Content)
	if err != nil {
		t.Fatalf("decode vision payload: %v", err)
	}
	return payload
}

func TestDetectMIMETypePrefersMagicBytes(t *testing.T) {
	jpegData := encodeJPEG(t, 4, 4, color.RGBA{R: 255, A: 255})
	if got := detectMIMEType(jpegData, "fake.png"); got != "image/jpeg" {
		t.Fatalf("detectMIMEType() = %q, want image/jpeg", got)
	}
}

